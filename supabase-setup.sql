drop policy if exists "Lectura publica de series" on public.series;
create policy "Lectura publica de series"
  on public.series for select to anon, authenticated
  using (true);

drop policy if exists "Usuarios autenticados crean series propias" on public.series;
create policy "Usuarios autenticados crean series propias"
  on public.series for insert to authenticated
  with check (
    auth.uid() = user_id
    and user_email = (select auth.jwt() ->> 'email')
  );

drop policy if exists "Cada usuario edita sus series" on public.series;
create policy "Cada usuario edita sus series"
  on public.series for update to authenticated
  using (auth.uid() = user_id)
  with check (
    auth.uid() = user_id
    and user_email = (select auth.jwt() ->> 'email')
  );

drop policy if exists "Cada usuario borra sus series" on public.series;
create policy "Cada usuario borra sus series"
  on public.series for delete to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Lectura publica de comentarios" on public.comentarios;
create policy "Lectura publica de comentarios"
  on public.comentarios for select to anon, authenticated
  using (true);

drop policy if exists "Usuarios autenticados crean comentarios propios" on public.comentarios;
create policy "Usuarios autenticados crean comentarios propios"
  on public.comentarios for insert to authenticated
  with check (
    auth.uid() = user_id
    and user_email = (select auth.jwt() ->> 'email')
  );

