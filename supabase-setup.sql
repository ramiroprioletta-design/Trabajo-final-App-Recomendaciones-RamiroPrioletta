update public.series as serie
set user_id = usuario.id
from auth.users as usuario
where serie.user_id is null
  and serie.user_email is not null
  and lower(serie.user_email) = lower(usuario.email);

update public.comentarios as comentario
set user_id = usuario.id
from auth.users as usuario
where comentario.user_id is null
  and comentario.user_email is not null
  and lower(comentario.user_email) = lower(usuario.email);

alter table public.series enable row level security;
