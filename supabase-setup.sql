drop policy if exists "Lectura publica de portadas" on storage.objects;
create policy "Lectura publica de portadas"
  on storage.objects for select to anon, authenticated
  using (bucket_id = 'portadas');

drop policy if exists "Usuarios suben sus propias portadas" on storage.objects;
create policy "Usuarios suben sus propias portadas"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'portadas'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

drop policy if exists "Usuarios borran sus propias portadas" on storage.objects;
create policy "Usuarios borran sus propias portadas"
  on storage.objects for delete to authenticated
  using (
    bucket_id = 'portadas'
    and (storage.foldername(name))[1] = auth.uid()::text
  );
